"""Derive the PostGIS version of find_candidates() from the portable one.

The portable function (haversine + bounding box) is what the test suite
exercises. The PostGIS version must differ only in the geo predicate, so it is
generated from the latest portable definition instead of being maintained by
hand. Run after changing find_candidates() in any migration:

    python supabase/tools/gen_postgis_find_candidates.py

Writes supabase/migrations/0099_find_candidates.postgis.sql, which sorts last so
nothing overrides it. Use --check in CI to fail if the file is stale.
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

MIGRATIONS = Path(__file__).resolve().parents[1] / "migrations"
OUT = MIGRATIONS / "0099_find_candidates.postgis.sql"

HEADER = """-- 0099: PostGIS find_candidates(). GENERATED by supabase/tools/gen_postgis_find_candidates.py
-- from the latest portable definition; do not edit by hand.
-- Differs from the portable version only in the distance and radius predicates,
-- which use the GiST indexes from 0007.

"""


def latest_definition() -> str:
    found = None
    for path in sorted(MIGRATIONS.glob("*.sql")):
        if path.name.endswith(".postgis.sql") or path.name.endswith(".supabase.sql"):
            continue
        text = path.read_text(encoding="utf8")
        for m in re.finditer(r"create (?:or replace )?function public\.find_candidates\(", text):
            end = text.index("$$;", text.index("language sql stable as $$", m.start())) + 3
            found = text[m.start():end]
    if not found:
        raise SystemExit("no portable find_candidates() found")
    return found


def build() -> str:
    fn = latest_definition()
    fn = re.sub(r"^create function", "create or replace function", fn)
    # a changed return type needs a drop first
    drop = "drop function if exists public.find_candidates(uuid, numeric, integer);\n\n"
    dist = "public.haversine_km(w.lat, w.lng, b.pickup_lat, b.pickup_lng) as dist,"
    if dist not in fn:
        raise SystemExit("distance expression not found; update the generator")
    fn = fn.replace(dist, "st_distance(w.geom, b.pickup_geom) / 1000.0 as dist,")
    box = re.search(r"       -- cheap bounding box first.*?(?=       and public\.workshop_open_at)", fn, re.S)
    if not box:
        raise SystemExit("bounding box predicate not found; update the generator")
    fn = fn.replace(box.group(0), "       -- uses the GiST index on workshops.geom\n       and st_dwithin(w.geom, b.pickup_geom, p_radius_km * 1000.0)\n")
    fn = fn.replace(
        "select bk.id, bk.service_id, bk.mode, bk.pickup_lat, bk.pickup_lng,",
        "select bk.id, bk.service_id, bk.mode, bk.pickup_lat, bk.pickup_lng, bk.pickup_geom,",
    )
    fn = fn.replace("create or replace function", "create function", 1)
    return HEADER + drop + fn + "\n"


def main(argv: list[str]) -> int:
    content = build()
    if "--check" in argv:
        if not OUT.exists() or OUT.read_text(encoding="utf8") != content:
            print("0099_find_candidates.postgis.sql is stale; run the generator")
            return 1
        return 0
    OUT.write_text(content, encoding="utf8", newline="\n")
    print(f"wrote {OUT.name}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
